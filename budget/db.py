"""Accès à la base : SQLite en local (un fichier), Postgres en ligne (Vercel + Neon).

Le reste du code écrit du SQL portable avec des paramètres « ? » ; cette couche
gomme les différences entre les deux moteurs :
  - paramètres « ? » traduits pour Postgres ;
  - lignes lisibles par nom (`r["name"]`) ou par position (`r[0]`) ;
  - `cursor.lastrowid` disponible sur les deux ;
  - types du schéma adaptés (identifiants, données binaires).
"""
from __future__ import annotations

import re
import sqlite3
import threading
from pathlib import Path

from flask import current_app, g

SCHEMA = Path(__file__).with_name("schema.sql")
# À augmenter quand schema.sql change : le schéma (idempotent) est alors rejoué au démarrage.
SCHEMA_VERSION = 4


def is_postgres(target: str) -> bool:
    return str(target).startswith(("postgres://", "postgresql://"))


class Row(tuple):
    """Ligne Postgres lisible comme une `sqlite3.Row` : par nom ou par position."""

    def __new__(cls, values, index):
        self = super().__new__(cls, values)
        self._index = index
        return self

    def __getitem__(self, key):
        if isinstance(key, str):
            return tuple.__getitem__(self, self._index[key])
        return tuple.__getitem__(self, key)

    def keys(self):
        return list(self._index)


def _row_factory(cursor):
    index = {c.name: i for i, c in enumerate(cursor.description or [])}
    return lambda values: Row(values, index)


# Tables sans colonne « id » : pas d'identifiant à récupérer après un INSERT.
NO_ID = {"credit_balances", "transfers_done", "login_attempts", "schema_version", "ticket_photos", "user_security", "import_files"}
_INSERT = re.compile(r"\s*INSERT\s+INTO\s+(\w+)", re.IGNORECASE)


class _PgCursor:
    def __init__(self, cur, lastrowid=None):
        self._cur = cur
        self.lastrowid = lastrowid      # identifiant créé par cet INSERT, relevé tout de suite
        self.rowcount = cur.rowcount

    def fetchone(self):
        return self._cur.fetchone()

    def fetchall(self):
        return self._cur.fetchall()

    def __iter__(self):
        return iter(self._cur.fetchall()) if self._cur.description else iter(())


class Database:
    """Connexion à l'un des deux moteurs, avec la même interface."""

    def __init__(self, target: str):
        self.target = str(target)
        self.postgres = is_postgres(self.target)
        self._sql_cache: dict[str, str] = {}
        if self.postgres:
            import psycopg

            # prepare_threshold=None : pas de requêtes préparées côté serveur, incompatibles avec
            # le regroupement de connexions de Neon (PgBouncer en mode transaction).
            self._conn = psycopg.connect(self.target, row_factory=_row_factory, connect_timeout=10,
                                         prepare_threshold=None)
        else:
            self._conn = sqlite3.connect(self.target, timeout=10)
            self._conn.row_factory = sqlite3.Row
            self._conn.execute("PRAGMA foreign_keys = ON")
            self._conn.execute("PRAGMA journal_mode = WAL")

    def _translate(self, sql: str) -> str:
        out = self._sql_cache.get(sql)
        if out is None:
            out = self._sql_cache[sql] = sql.replace("%", "%%").replace("?", "%s")
        return out

    def execute(self, sql: str, params=()):
        if not self.postgres:
            return self._conn.execute(sql, tuple(params))
        m = _INSERT.match(sql)
        if m and m.group(1).lower() not in NO_ID and "RETURNING" not in sql.upper():
            cur = self._conn.execute(self._translate(sql) + " RETURNING id", tuple(params))
            row = cur.fetchone()
            return _PgCursor(cur, row[0] if row else None)
        return _PgCursor(self._conn.execute(self._translate(sql), tuple(params)))

    def executescript(self, script: str) -> None:
        """Exécute plusieurs instructions (schéma). Les commentaires SQL sont retirés."""
        script = re.sub(r"--[^\n]*", "", script)
        for stmt in (s.strip() for s in script.split(";")):
            if not stmt:
                continue
            if self.postgres:
                stmt = re.sub(r"INTEGER PRIMARY KEY(?! REFERENCES)", "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", stmt)
                stmt = stmt.replace("BLOB", "BYTEA")
            self.execute(stmt)

    def commit(self) -> None:
        self._conn.commit()

    def rollback(self) -> None:
        self._conn.rollback()

    def close(self) -> None:
        self._conn.close()

    @property
    def usable(self) -> bool:
        return not (self.postgres and (self._conn.closed or self._conn.broken))


def connect(target: str) -> Database:
    return Database(target)


# Sur Vercel, une instance sert plusieurs requêtes à la suite : on garde la connexion
# Postgres ouverte plutôt que de refaire la poignée de main TLS à chaque page.
# Une connexion par fil d'exécution : deux requêtes simultanées ne partagent jamais une transaction.
_local = threading.local()
_all: list[Database] = []


def _shared() -> dict[str, Database]:
    if not hasattr(_local, "conns"):
        _local.conns = {}
    return _local.conns


def get_db() -> Database:
    if "db" not in g:
        target = current_app.config["DATABASE"]
        if is_postgres(target):
            db = _shared().get(target)
            if db is None or not db.usable:
                db = _shared()[target] = connect(target)
                _all.append(db)
            g.db = db
        else:
            g.db = connect(target)
    return g.db


def close_db(_exc=None) -> None:
    db = g.pop("db", None)
    if db is None:
        return
    if db.postgres:
        try:
            db.rollback()      # rien de non validé ne doit fuir vers la requête suivante
        except Exception:      # connexion perdue : elle sera rouverte à la prochaine requête
            _shared().pop(db.target, None)
    else:
        db.close()


def reset_shared() -> None:
    """Ferme les connexions gardées ouvertes (tests)."""
    for db in _all:
        try:
            db.close()
        except Exception:
            pass
    _all.clear()
    _shared().clear()


def init_schema(conn: Database) -> None:
    """Crée ou met à jour les tables, seulement si le schéma a changé."""
    try:
        row = conn.execute("SELECT version FROM schema_version").fetchone()
        current = row["version"] if row else 0
    except Exception:
        conn.rollback()
        current = 0
    if current >= SCHEMA_VERSION:
        return
    conn.executescript(SCHEMA.read_text(encoding="utf-8"))
    conn.execute("DELETE FROM schema_version")
    conn.execute("INSERT INTO schema_version (version) VALUES (?)", (SCHEMA_VERSION,))
    conn.commit()


def ensure_user(conn: Database, name: str = "fred") -> int:
    row = conn.execute("SELECT id FROM users WHERE name = ?", (name,)).fetchone()
    if row:
        return row["id"]
    cur = conn.execute("INSERT INTO users (name) VALUES (?)", (name,))
    user_id = cur.lastrowid
    conn.commit()
    return user_id


def sync_accounts(conn: Database, user_id: int, settings) -> None:
    """Crée les comptes déclarés dans settings.toml et met à jour leur ordre."""
    for i, c in enumerate(settings.comptes):
        conn.execute(
            "INSERT INTO accounts (user_id, name, sort) VALUES (?, ?, ?) "
            "ON CONFLICT(user_id, name) DO UPDATE SET sort = excluded.sort",
            (user_id, c.nom, i),
        )
    conn.commit()


def backup_to(src_path: str, dest_path: str) -> None:
    """Copie cohérente d'une base SQLite (API de sauvegarde, sûre pendant l'utilisation)."""
    src = sqlite3.connect(src_path)
    dst = sqlite3.connect(dest_path)
    with dst:
        src.backup(dst)
    dst.close()
    src.close()
